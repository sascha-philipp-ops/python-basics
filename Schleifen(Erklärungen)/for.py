# Aufgabe: Zähle von 1 bis 5


for i in range (1, 6): 
    # range(1, 6) bedeutet: Start bei 1, Stopp VOR 6
    # Der Code hier drin läuft für jede Zahl einmal
    print(f"Durchgang Nummer {i}") 

